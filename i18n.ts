export const dictionaries: Record<Lang, Dict> = { ru, kk };

export function translate(lang: Lang, key: TKey, params?: Record<string, string | number>) {
  let s: string = dictionaries[lang][key] ?? dictionaries.ru[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** Russian-style pluralization; Kazakh has no plural agreement so returns the same word. */
export function plural(lang: Lang, n: number, one: TKey, few: TKey, many: TKey) {
  if (lang === "kk") return dictionaries.kk[one];
  const d = dictionaries.ru;
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return d[one];
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return d[few];
  return d[many];
}
